-- Library schema (architecture 5.2, D2). Executed by Spring SQL init on every start (database is in-memory);
-- Hibernate then validates the entity mapping against it (ddl-auto=validate).
-- Constraint names are load-bearing: ConstraintViolationTranslator maps them to error codes (architecture 6.2.1).
-- H2 reports unquoted names in upper case, so names are compared case-insensitively.

CREATE TABLE book (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             VARCHAR(255) NOT NULL,
    author            VARCHAR(255) NOT NULL,
    isbn              VARCHAR(13)  NOT NULL,
    total_copies      INT          NOT NULL,
    active_loan_count INT          NOT NULL DEFAULT 0,
    version           BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_book_isbn UNIQUE (isbn),
    CONSTRAINT ck_book_total_copies CHECK (total_copies BETWEEN 1 AND 999),
    CONSTRAINT ck_book_active_loans CHECK (active_loan_count >= 0 AND active_loan_count <= total_copies)
);

CREATE INDEX ix_book_title_isbn ON book (title, isbn);

CREATE TABLE member (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(100) NOT NULL,
    email             VARCHAR(254) NOT NULL,
    email_normalized  VARCHAR(254) NOT NULL,
    status            VARCHAR(8)   NOT NULL,
    active_loan_count INT          NOT NULL DEFAULT 0,
    version           BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_member_email UNIQUE (email_normalized),
    CONSTRAINT ck_member_status CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT ck_member_active_loans CHECK (active_loan_count BETWEEN 0 AND 3),
    CONSTRAINT ck_member_inactive_no_loans CHECK (status = 'ACTIVE' OR active_loan_count = 0)
);

CREATE INDEX ix_member_name_id ON member (name, id);
CREATE INDEX ix_member_status ON member (status);

CREATE TABLE loan (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id      BIGINT NOT NULL,
    book_id        BIGINT NOT NULL,
    checkout_date  DATE   NOT NULL,
    due_date       DATE   NOT NULL,
    return_date    DATE,
    active_book_id BIGINT,
    CONSTRAINT fk_loan_member FOREIGN KEY (member_id) REFERENCES member (id),
    CONSTRAINT fk_loan_book FOREIGN KEY (book_id) REFERENCES book (id),
    CONSTRAINT ck_loan_due CHECK (due_date >= checkout_date),
    CONSTRAINT ck_loan_return CHECK (return_date IS NULL OR return_date >= checkout_date),
    -- "active_book_id IS NOT NULL" is explicit on purpose: with SQL three-valued logic, "NULL = book_id" is UNKNOWN and a
    -- CHECK treats UNKNOWN as satisfied, so without it an active loan with active_book_id NULL would slip through
    -- (and escape uk_loan_member_active_book). Architecture 5.2 states the intent: book_id while active, else NULL.
    CONSTRAINT ck_loan_active_key CHECK (
        (return_date IS NULL AND active_book_id IS NOT NULL AND active_book_id = book_id)
        OR (return_date IS NOT NULL AND active_book_id IS NULL)),
    -- H2 allows several NULLs in a unique key, so only ACTIVE loans (active_book_id = book_id) are constrained:
    -- one active loan per member per book (AC-4.BE.5). Portable substitute for a partial unique index.
    CONSTRAINT uk_loan_member_active_book UNIQUE (member_id, active_book_id)
);

CREATE INDEX ix_loan_member_active ON loan (member_id, return_date);
CREATE INDEX ix_loan_book_active ON loan (book_id, return_date);
CREATE INDEX ix_loan_overdue ON loan (return_date, due_date);
